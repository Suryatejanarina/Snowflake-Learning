-- Step 1: Create a file format for CSV files
-- Step 2: Create the target table
-- Step 3: Load the file using the Snowsight UI

USE DATABASE LEARNING;
USE SCHEMA LEARNING_SCHEMA;

-- Step 1: Create the CSV file format
CREATE OR REPLACE FILE FORMAT CSV_FF
  TYPE = 'CSV'                 -- type of file this format reads
  SKIP_HEADER = 1              -- number of header lines to skip (1 = skip the first line)
  FIELD_DELIMITER = ','        -- character that separates columns (default is comma)
  RECORD_DELIMITER = '\n';     -- character that separates rows (default is newline)

-- Check the file formats and their settings
SHOW FILE FORMATS;
DESC FILE FORMAT CSV_FF;

-- Step 2: Create the target table
CREATE TABLE IF NOT EXISTS EMPLOYEE (
    Emp_id   INT,
    Emp_name VARCHAR(50),
    Company  VARCHAR(30),
    JoinDate DATE,
    Country  VARCHAR(30)
);

-- Step 3: Load the file (this COPY command was generated by the Snowsight UI)
COPY INTO "LEARNING"."LEARNING_SCHEMA"."EMPLOYEE"
FROM (
    SELECT $1, $2, $3, $4, $5      -- $1 to $5 = file columns by position
    FROM '@"LEARNING"."LEARNING_SCHEMA"."__snowflake_temp_import_files__"'
)
FILES = ('2026-11-09T13:55:52.331Z/employee.csv')
FILE_FORMAT = (FORMAT_NAME = "LEARNING"."LEARNING_SCHEMA"."CSV_FF")  -- tells Snowflake how to read the file
ON_ERROR = ABORT_STATEMENT;        -- stop the load if any row has an error

-- Verify the load
SELECT * FROM EMPLOYEE;


-- Other useful CSV file format options (apply to future loads)

-- Values wrapped in quotes are treated as one value, so a comma inside quotes
-- (for example "Hyderabad, India") is not read as a column separator
ALTER FILE FORMAT CSV_FF SET FIELD_OPTIONALLY_ENCLOSED_BY = '"';

-- Do not fail when the number of columns in the file differs from the table
-- (missing values load as NULL)
ALTER FILE FORMAT CSV_FF SET ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

-- Set the date format of the file (default is AUTO, which detects common formats)
ALTER FILE FORMAT CSV_FF SET DATE_FORMAT = 'DD-MM-YYYY';



-- Create a file format for JSON files
CREATE OR REPLACE FILE FORMAT JSON_FF
  TYPE = 'JSON'
  STRIP_OUTER_ARRAY = TRUE      -- split a top-level array into one row per element
  STRIP_NULL_VALUES = FALSE     -- keep keys that have null values
  COMPRESSION = AUTO            -- detect compression automatically
  ALLOW_DUPLICATE = FALSE       -- do not allow duplicate keys in an object
  TRIM_SPACE = TRUE;            -- remove extra spaces around string values

DESC FILE FORMAT JSON_FF;

-- Table with a single VARIANT column to hold each JSON record
CREATE TABLE IF NOT EXISTS EMPLOYEE_JSON (
    raw_data VARIANT
);

-- Load the JSON file from a stage (replace @emp_stage with your stage)
COPY INTO EMPLOYEE_JSON
FROM @emp_stage/employee.json
FILE_FORMAT = (FORMAT_NAME = 'JSON_FF')
ON_ERROR = ABORT_STATEMENT;

-- Query the JSON fields (path notation plus a cast)
SELECT raw_data:Emp_id::INT      AS emp_id,
       raw_data:Emp_name::STRING AS emp_name,
       raw_data:Company::STRING  AS company
FROM EMPLOYEE_JSON;
